const DICTS = { en, ru };

const LangCtx = createContext(null);

function detectLang() {
  if (typeof localStorage !== "undefined" && localStorage.getItem("nexus_lang")) return localStorage.getItem("nexus_lang");
  return (navigator.language || "en").toLowerCase().startsWith("ru") ? "ru" : "en";
}

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(detectLang);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((next) => {
    const l = next === "ru" ? "ru" : "en";
    setLangState(l);
    try {
      localStorage.setItem("nexus_lang", l);
    } catch {
      /* private mode */
    }
    api("/auth/language", { method: "POST", body: { lang: l } }).catch(() => {});
  }, []);

  const value = useMemo(() => {
    const dict = DICTS[lang] || en;
    const t = (key, vars) => {
      let s = dict[key] ?? en[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    };
    const err = (code) => dict[`err_${code}`] ?? en[`err_${code}`] ?? (typeof code === "string" ? code.replace(/_/g, " ") : String(code));
    return { lang, setLang, t, err, dict };
  }, [lang, setLang]);

  return <LangCtx.Provider value={value}>{children}</LangCtx.Provider>;
}

export const useLang = () => useContext(LangCtx) || { lang: "en", setLang: () => {}, t: (k) => k, err: (k) => k };
export const useT = () => useLang().t;
export const useErr = () => useLang().err;
